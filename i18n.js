let LANG = localStorage.getItem("ws_lang") || "vi";

function t(key, ...args) {
  const v = (I18N[LANG] || I18N.vi)[key];
  return typeof v === "function" ? v(...args) : v == null ? key : v;
}

function applyLang(lang) {
  LANG = I18N[lang] ? lang : "vi";
  localStorage.setItem("ws_lang", LANG);
  document.documentElement.lang = LANG === "zh" ? "zh-Hant" : LANG;
  document.title = t("appDocTitle");
  // static text nodes
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const value = t(el.getAttribute("data-i18n"));
    el.textContent = value;
    el.hidden = value === "";
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-ph")));
  });
  // active state on switch buttons
  document.querySelectorAll(".lang-switch button").forEach((b) =>
    b.classList.toggle("active", b.getAttribute("data-lang") === LANG)
  );
  // let app.js refresh dynamically-built strings (book/lesson dropdowns)
  if (typeof window.refreshDynamicI18n === "function") window.refreshDynamicI18n();
}

window.addEventListener("DOMContentLoaded", () => {
  document.querySelectorAll(".lang-switch button").forEach((b) =>
    b.addEventListener("click", () => applyLang(b.getAttribute("data-lang")))
  );
  applyLang(LANG);
});
